def create_curriculum(root: Path, dry_run: bool = False):
    created_dirs = 0
    created_files = 0
    skipped_files = 0

    root.mkdir(parents=True, exist_ok=True)

    for package_name, subfolders in CURRICULUM:
        package_path = root / package_name

        for subfolder_index, (subfolder_name, concepts) in enumerate(
            subfolders.items()
        ):
            folder_path = package_path / subfolder_name

            if not folder_path.exists():
                print(f"[DIR]  {folder_path.relative_to(root)}")
                if not dry_run:
                    folder_path.mkdir(parents=True, exist_ok=True)
                created_dirs += 1

            for note_index, concept in enumerate(concepts):
                filename = f"{note_index:02d} - {concept}.md"
                note_path = folder_path / filename

                if note_path.exists():
                    skipped_files += 1
                    continue

                print(f"[FILE] {note_path.relative_to(root)}")

                if not dry_run:
                    note_path.write_text(
                        "[[Computer Science]]\n",
                        encoding="utf-8"
                    )

                created_files += 1

    print("\n========== CURRICULUM SUMMARY ==========")
    print(f"Root:             {root}")
    print(f"Directories:      {created_dirs}")
    print(f"Files created:    {created_files}")
    print(f"Files skipped:    {skipped_files}")
    print(f"Dry run:          {dry_run}")
    print("========================================")


def main():
    parser = argparse.ArgumentParser(
        description="Generate the Computer Science Obsidian curriculum."
    )

    parser.add_argument(
        "--root",
        type=Path,
        default=Path.cwd(),
        help="Target Computer Science directory (default: current directory)."
    )

    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Preview the files without creating them."
    )

    args = parser.parse_args()

    create_curriculum(args.root.resolve(), args.dry_run)


if __name__ == "__main__":
    main()
